import { createInterface } from 'node:readline';
import { fileURLToPath } from 'node:url';
import { normalize, saveConfig } from '../src/config.mjs';
import { createContext } from '../src/core.mjs';
import { createMcp } from '../src/server.mjs';
import { createLiveMcp } from '../src/live-mcp.mjs';
import { hashToken } from '../src/mcp-agents.mjs';

test('a running connection reloads privacy and revocation changes before its next request', async (t) => {
  const root = await mkdtemp(path.join(tmpdir(), 'brainlink-live-config-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const vault = path.join(root, 'vault');
  await mkdir(path.join(vault, 'Inbox'), { recursive: true });
  await writeFile(path.join(vault, 'Note.md'), '# Note\n\nFictional content.\n');
  const token = 'fictional-revocable-agent-token';
  const env = { HOME: root, BRAINLINK_HOME: path.join(root, 'app'), BRAINLINK_SEMANTIC: '0', BRAINLINK_AI_PLATFORM: 'Fictional', BRAINLINK_AGENT_TOKEN: token };
  const configFile = path.join(env.BRAINLINK_HOME, 'config.json');
  let cfg = normalize({ vaults: [{ name: 'Vault', path: vault, writes: 'on' }], ai_agents: [{ id: 'fictional', name: 'Fictional agent', kind: 'local', tokenHash: hashToken(token) }] });
  await saveConfig(cfg, configFile);
  const initialContext = createContext(cfg, { env });
  const live = createLiveMcp({ env, initialConfig: cfg, initialContext, createServer: (ctx) => createMcp(ctx) });
  const call = (name, args) => live.handleBody({ jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name, arguments: args } });
  assert.match(JSON.stringify(await call('vault_read_note', { vault: 'Vault', path: 'Note.md' })), /Fictional content/);
  cfg = normalize({ ...cfg, vaults: [{ ...cfg.vaults[0], private: true }] });
  await saveConfig(cfg, configFile);
  const proposal = await call('propose_note', { vault: 'Vault', folder: 'Inbox', title: 'New idea', body: 'Fictional idea', source: 'fixture', confirm: true });
  assert.equal(proposal.result.structuredContent.written, false, JSON.stringify(proposal));
  assert.deepEqual(await readdir(path.join(vault, 'Inbox')), []);
  cfg = normalize({ ...cfg, ai_agents: [{ ...cfg.ai_agents[0], revoked: true, tokenHash: null }] });
  await saveConfig(cfg, configFile);
  const afterRevoke = await call('vault_read_note', { vault: 'Vault', path: 'Note.md' });
  assert.doesNotMatch(JSON.stringify(afterRevoke), /Fictional content/);
  assert.equal(afterRevoke.result.isError, true);
  await writeFile(configFile, '{ invalid config');
  const badConfig = await call('vault_read_note', { vault: 'Vault', path: 'Note.md' });
  assert.ok(badConfig.error);
  assert.doesNotMatch(JSON.stringify(badConfig), /Fictional content/);
});

test('the running stdio server applies a newly private vault before its next write', async (t) => {
  const root = await mkdtemp(path.join(tmpdir(), 'brainlink-live-stdio-'));
  const vault = path.join(root, 'vault');
  await mkdir(path.join(vault, 'Inbox'), { recursive: true });
  const token = 'fictional-stdio-agent-token';
  const env = { ...process.env, HOME: root, BRAINLINK_HOME: path.join(root, 'app'), BRAINLINK_SEMANTIC: '0', BRAINLINK_AI_PLATFORM: 'Fictional', BRAINLINK_AGENT_TOKEN: token };
  const configFile = path.join(env.BRAINLINK_HOME, 'config.json');
  let cfg = normalize({ vaults: [{ name: 'Vault', path: vault, writes: 'on' }], ai_agents: [{ id: 'fictional', name: 'Fictional agent', kind: 'local', tokenHash: hashToken(token) }] });
  await saveConfig(cfg, configFile);
  const cli = fileURLToPath(new URL('../bin/brainlink.mjs', import.meta.url));
  const child = spawn(process.execPath, [cli, 'serve'], { env, stdio: ['pipe', 'pipe', 'pipe'] });
  const lines = createInterface({ input: child.stdout });
  const pending = new Map();
  lines.on('line', (line) => { const reply = JSON.parse(line); pending.get(reply.id)?.(reply); pending.delete(reply.id); });
  t.after(async () => { child.kill(); lines.close(); await rm(root, { recursive: true, force: true }); });
  const call = (id, method, params = {}) => new Promise((resolve, reject) => {
    const timeout = setTimeout(() => { pending.delete(id); reject(new Error('Timed out waiting for the fictional server.')); }, 10000);
    pending.set(id, (reply) => { clearTimeout(timeout); resolve(reply); });
    child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id, method, params }) + '\n');
  });
  assert.ok((await call(1, 'initialize')).result);
  await writeFile(path.join(vault, 'Note.md'), '# Note\n\nFictional content.\n');
  const read = await call(2, 'tools/call', { name: 'vault_read_note', arguments: { vault: 'Vault', path: 'Note.md' } });
  assert.match(JSON.stringify(read), /Fictional content/);
  const afterUse = JSON.parse(await readFile(configFile, 'utf8'));
  assert.equal(afterUse.ai_agents[0].lastSeenAt, null, 'ordinary MCP use must not rewrite settings or connection state');
  cfg = normalize({ ...cfg, vaults: [{ ...cfg.vaults[0], private: true }] });
  await saveConfig(cfg, configFile);
  const reply = await call(3, 'tools/call', { name: 'propose_note', arguments: { vault: 'Vault', folder: 'Inbox', title: 'Fictional', body: 'Only a proposal', source: 'fixture', confirm: true } });
  assert.equal(reply.result.structuredContent.written, false, JSON.stringify(reply));
  assert.deepEqual(await readdir(path.join(vault, 'Inbox')), []);
});

test('an HTTP listener refuses requests after its saved bearer token changes', async (t) => {
  const root = await mkdtemp(path.join(tmpdir(), 'brainlink-live-http-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const env = { HOME: root, BRAINLINK_HOME: path.join(root, 'app'), BRAINLINK_SEMANTIC: '0' };
  const file = path.join(env.BRAINLINK_HOME, 'config.json');
  let cfg = normalize({ http: { port: 8765, token: 'fictional-old-token-value' } });
  await saveConfig(cfg, file);
  const live = createLiveMcp({ env, initialConfig: cfg, initialContext: createContext(cfg, { env }), createServer: (ctx) => createMcp(ctx), httpTokenFromConfig: true });
  assert.ok((await live.handleBody({ jsonrpc: '2.0', id: 1, method: 'ping' })).result);
  cfg = normalize({ ...cfg, http: { ...cfg.http, token: 'fictional-new-token-value' } });
  await saveConfig(cfg, file);
  assert.ok((await live.handleBody({ jsonrpc: '2.0', id: 2, method: 'ping' })).error);
});
